'use strict';
const router=require('express').Router();
const auth=require('../middleware/auth.middleware');
const {requirePermission}=require('../middleware/permission.middleware');
const c=require('../controllers/letter.controller');
const permit=action=>[auth,requirePermission('DOCUMENTS',action)];
router.get('/documents/letters',...permit('VIEW'),c.index);
router.get('/documents/letters/new',...permit('CREATE'),c.editor);
router.get('/documents/letters/export/excel',...permit('EXPORT'),c.excel);
router.get('/documents/letters/:id/edit',...permit('EDIT'),c.editor);
router.get('/documents/letters/:id/preview',...permit('VIEW'),c.html);
router.get('/documents/letters/:id/print',...permit('PRINT'),c.html);
router.get('/documents/letters/:id/pdf',...permit('EXPORT'),c.pdf);
router.get('/documents/letters/:id/excel',...permit('EXPORT'),c.excel);
router.get('/documents/letters/:id',...permit('VIEW'),c.view);
router.post('/api/letters/preview',...permit('VIEW'),c.preview);
router.post('/api/letters/content-preview',...permit('VIEW'),c.contentPreview);
router.post('/api/letters',...permit('CREATE'),c.create);
router.put('/api/letters/:id',...permit('EDIT'),c.update);
router.post('/api/letters/:id/void',...permit('VOID'),c.action('VOIDED'));
router.post('/api/letters/:id/delete',...permit('DELETE'),c.action('DELETED'));
router.post('/api/letters/:id/restore',...permit('RESTORE'),c.action('RESTORED'));
module.exports=router;
